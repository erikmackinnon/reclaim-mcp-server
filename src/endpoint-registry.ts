const endpointBySignature = new Map<string, EndpointRegistryEntry>();

for (const entry of ENDPOINT_REGISTRY) {
  endpointBySignature.set(entry.method + " " + entry.pathTemplate, entry);
}

function splitPathSegments(value: string): string[] {
  return value.split("/").filter((segment) => segment.length > 0);
}

function matchesPathTemplate(template: string, requestPath: string): boolean {
  const templateSegments = splitPathSegments(template);
  const requestSegments = splitPathSegments(requestPath);

  if (templateSegments.length !== requestSegments.length) {
    return false;
  }

  return templateSegments.every((segment, index) => {
    const requestSegment = requestSegments[index];
    if (!requestSegment) {
      return false;
    }

    if (segment === "*") {
      return true;
    }
    if (segment.startsWith("{") && segment.endsWith("}")) {
      return true;
    }
    return segment === requestSegment;
  });
}

function pathTemplateSpecificityScore(template: string): number {
  return splitPathSegments(template).reduce((score, segment) => {
    if (segment === "*") {
      return score;
    }
    if (segment.startsWith("{") && segment.endsWith("}")) {
      return score + 1;
    }
    return score + 2;
  }, 0);
}

export function listEndpointRegistry(): readonly EndpointRegistryEntry[] {
  return ENDPOINT_REGISTRY;
}

export function getEndpointBySignature(
  method: HttpMethod,
  pathTemplate: string,
): EndpointRegistryEntry | undefined {
  return endpointBySignature.get(method + " " + pathTemplate);
}

export function matchEndpointRequest(
  method: HttpMethod,
  requestPath: string,
): EndpointRegistryEntry | undefined {
  let bestMatch: EndpointRegistryEntry | undefined;
  let bestScore = -1;

  for (const entry of ENDPOINT_REGISTRY) {
    if (entry.method !== method) {
      continue;
    }
    if (!matchesPathTemplate(entry.pathTemplate, requestPath)) {
      continue;
    }

    const score = pathTemplateSpecificityScore(entry.pathTemplate);
    if (score > bestScore) {
      bestMatch = entry;
      bestScore = score;
    }
  }

  return bestMatch;
}

export function listEndpointMatchesForPath(
  requestPath: string,
): readonly EndpointRegistryEntry[] {
  return ENDPOINT_REGISTRY.filter((entry) =>
    matchesPathTemplate(entry.pathTemplate, requestPath),
  );
}
