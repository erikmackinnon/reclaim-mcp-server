export type ExposureMode = "typed" | "raw" | "excluded";

export const EXCLUSION_CATEGORIES = [
  "staff",
  "admin",
  "billing",
  "oauth",
  "api_key",
  "scim",
  "webhook_admin",
  "callback_route",
] as const;

export type ExclusionCategory = (typeof EXCLUSION_CATEGORIES)[number];

export type EndpointSafetyFlags = {
  readOnly: boolean;
  destructive: boolean;
  bulk: boolean;
  highRisk: boolean;
};

export type EndpointRegistryEntry = {
  domain: EndpointDomain;
  pathTemplate: string;
  method: HttpMethod;
  allowedMethods: readonly HttpMethod[];
  mode: ExposureMode;
  isExcluded: boolean;
  exclusionCategory?: ExclusionCategory;
  exclusionReason?: string;
  safety: EndpointSafetyFlags;
  description: string;
};

