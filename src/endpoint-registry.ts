/**
 * Endpoint registry for the Reclaim API surface.
 *
 * This module is the canonical source of truth for endpoint scope decisions in WU-01.
 * Every endpoint in API-SURFACE.md must map to exactly one mode:
 * - typed: exposed through structured MCP tools/resources
 * - raw: available to future constrained raw fallback
 * - excluded: blocked by policy
 */

